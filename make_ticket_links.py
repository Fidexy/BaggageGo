#!/usr/bin/env python3
"""Write ``tickets.md``: every ticket in the db as a clickable link.

    .venv/bin/python make_ticket_links.py            # -> tickets.md
    .venv/bin/python make_ticket_links.py --stdout   # print, write nothing

The link is built from ``server_v1.PUBLIC_BASE`` + ``server_v1.BASE`` rather than
from a literal here: there is one place to look before a print run, and this file is
not a second one. Override the base to point the list somewhere else without
reprinting anything — the ``<CODE>`` is host-independent, so the same code opens the
same booking on any host that runs this app:

    BGGO_PUBLIC_BASE=https://<host> .venv/bin/python make_ticket_links.py

When the base differs from ``PRINTED_BASE`` the file says so, because the sentence
"this is the URL on the paper" is then false.

Read-only, like the QR generator: links are a view of the database, never a
source of it. Order is id order, which is also seat order (front to back), so the
list reads like the manifest.
"""
from __future__ import annotations

import argparse
import sqlite3
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from server_v1 import BASE, PUBLIC_BASE  # noqa: E402  (path set above)

DB_PATH = HERE / "passengers.db"
OUT_PATH = HERE / "tickets.md"

# Frozen: what the printed QR codes encode (D9). Not to be confused with
# PUBLIC_BASE, which is where these *links* point — they are the same hostname
# until someone overrides it for a copy hosted elsewhere.
PRINTED_BASE = "https://sophon1.dedyn.io"


def ticket_url(code: str, base: str = PUBLIC_BASE) -> str:
    return f"{base}{BASE}/{code}"


def load_rows(db_path: Path) -> list[dict]:
    """Named slots only: an unallocated slot opens the "no booking" page."""
    uri = f"file:{db_path}?mode=ro"
    con = sqlite3.connect(uri, uri=True)
    con.row_factory = sqlite3.Row
    try:
        rows = con.execute(
            """
            SELECT id, code, full_name, seat_number
              FROM passengers
             WHERE full_name IS NOT NULL AND TRIM(full_name) <> ''
             ORDER BY id
            """
        ).fetchall()
    finally:
        con.close()
    return [dict(r) for r in rows]


def render(rows: list[dict], base: str = PUBLIC_BASE) -> str:
    """The list, with the same shape whatever the base is.

    That is deliberate: hosting the demo elsewhere means regenerating this file with
    a different base (`BGGO_PUBLIC_BASE`), and the two renderings have to be
    identical apart from the base itself, so the difference can be *verified* rather
    than assumed. So there is no conditional prose here — one fixed block, two
    hostnames named, and an explanation that is true in both cases.
    """
    out = [
        "# BaggageGO — every ticket link",
        "",
        f"All **{len(rows)}** passengers in `passengers.db`, in seat order. Generated by",
        "`make_ticket_links.py`; re-run it after any reseed, do not hand-edit.",
        "",
        f"Payload printed in the QR (frozen): `{PRINTED_BASE}{BASE}/<CODE>`",
        f"These links open: `{base}{BASE}/<CODE>`",
        "",
        "The `<CODE>` is host-independent — the same code opens the same booking on any",
        "host that runs this app — so a difference between those two lines only decides",
        "which machine answers. Nothing on paper changes if this list points elsewhere.",
        "",
        f"Board: [{base}{BASE}/live]({base}{BASE}/live)",
        "",
        "Opening a link does **not** mark that passenger as scanned — the card only",
        "records a scan when a bag is chosen (or `POST /bggo/api/scan` is called), so",
        "this list is safe to click through while testing. The board is cleared with",
        "`POST /bggo/api/reset` plus the `X-Board-Token` header",
        "(`.venv/bin/python server_v1.py --token`).",
        "",
        "| # | Seat | Passenger | Ticket code | Link |",
        "|---:|:---:|---|---|---|",
    ]
    for r in rows:
        url = ticket_url(r["code"], base)
        out.append(
            f"| {r['id']} | {r['seat_number']} | {r['full_name']} | "
            f"`{r['code']}` | [open]({url}) |"
        )
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--db", type=Path, default=DB_PATH, help=f"SQLite db (default: {DB_PATH})")
    ap.add_argument("--out", type=Path, default=OUT_PATH, help=f"markdown file (default: {OUT_PATH})")
    ap.add_argument("--stdout", action="store_true", help="print the markdown, write nothing")
    args = ap.parse_args(argv)

    if not args.db.is_file():
        print(f"error: no database at {args.db}", file=sys.stderr)
        return 1

    rows = load_rows(args.db)
    if not rows:
        print("error: no allocated passengers — nothing to link", file=sys.stderr)
        return 1

    text = render(rows)
    if args.stdout:
        print(text)
        return 0

    args.out.write_text(text, encoding="utf-8")
    print(f"{len(rows)} ticket links -> {args.out.relative_to(HERE.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
